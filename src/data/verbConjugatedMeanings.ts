/**
 * VerbCardItem.id ('u1-1') 또는 VerbWorksheetItem.id ('1-1') 모두로 활용형 모국어 뜻을 조회합니다.
 */
export function getVerbConjugatedMeaning(
  id: string,
  lang: SupportedLanguage
): string | undefined {
  const normalized = id.startsWith('u') ? id.slice(1) : id;
  const entry = VERB_CONJUGATED_MEANINGS[normalized];
  if (!entry) return undefined;
  return entry[lang] || entry.en;
}
