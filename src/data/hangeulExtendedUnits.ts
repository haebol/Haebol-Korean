import type { HangeulUnitGroup, HangeulCardData } from './hangeulGroupsData';

type LangRecord = HangeulCardData['meanings'];

const makeCombinationTips = (
  c: string,
  cRom: string,
  v: string,
  vRom: string,
  s: string,
  sRom: string,
  mode: 'horizontal' | 'compound'
): LangRecord => {
  if (mode === 'compound') {
    return {
      en: `Consonant [${c}]${cRom} + Compound Vowel [${v}]${vRom} combine into [${s}]${sRom}.`,
      vi: `Phụ âm [${c}]${cRom} + Nguyên âm kép [${v}]${vRom} kết hợp thành [${s}]${sRom}.`,
      bn: `ব্যঞ্জনবর্ণ [${c}]${cRom} + যৌগিক স্বরবর্ণ [${v}]${vRom} যুক্ত হয়ে [${s}]${sRom} তৈরি হয়।`,
      zh: `声母 [${c}]${cRom} + 复合韵母 [${v}]${vRom} 拼合成 [${s}]${sRom}。`,
      ru: `Согласный [${c}]${cRom} + сложный гласный [${v}]${vRom} образуют [${s}]${sRom}.`,
      ja: `子音 [${c}]${cRom} + 複合母音 [${v}]${vRom} が合わさって [${s}]${sRom} になります。`,
      mn: `Гийгүүлэгч [${c}]${cRom} ба нийлмэл эгшиг [${v}]${vRom} нийлж [${s}]${sRom} болно.`,
    };
  }
  return {
    en: `Consonant [${c}]${cRom} + Vowel [${v}]${vRom} combine horizontally into [${s}]${sRom}.`,
    vi: `Phụ âm [${c}]${cRom} + Nguyên âm [${v}]${vRom} kết hợp trái phải thành [${s}]${sRom}.`,
    bn: `ব্যঞ্জনবর্ণ [${c}]${cRom} + স্বরবর্ণ [${v}]${vRom} পাশাপাশি যুক্ত হয়ে [${s}]${sRom} তৈরি হয়।`,
    zh: `声母 [${c}]${cRom} + 韵母 [${v}]${vRom} 左右拼合成 [${s}]${sRom}。`,
    ru: `Согласный [${c}]${cRom} + гласный [${v}]${vRom} соединяются слева направо в [${s}]${sRom}.`,
    ja: `子音 [${c}]${cRom} + 母音 [${v}]${vRom} が左右に合わさって [${s}]${sRom} になります。`,
    mn: `Гийгүүлэгч [${c}]${cRom} ба эгшиг [${v}]${vRom} зүүнээс баруун тийш нийлж [${s}]${sRom} болно.`,
  };
};

const makeWordCombineTips = (
  parts: { char: string; rom: string }[],
  word: string,
  meanings: LangRecord
): LangRecord => {
  const joinExpr = parts.map((p) => `[${p.char}]${p.rom}`).join(' + ');
  return {
    en: `${joinExpr} combine to make the word [${word}](${meanings.en})!`,
    vi: `${joinExpr} kết hợp tạo thành từ [${word}](${meanings.vi})!`,
    bn: `${joinExpr} যুক্ত হয়ে [${word}](${meanings.bn}) শব্দটি গঠিত হয়!`,
    zh: `${joinExpr} 组合成单词 [${word}](${meanings.zh})！`,
    ru: `${joinExpr} соединяются и образуют слово [${word}](${meanings.ru})!`,
    ja: `${joinExpr} が合わさって単語 [${word}](${meanings.ja}) になります！`,
    mn: `${joinExpr} нийлж [${word}](${meanings.mn}) үг бүтдэг!`,
  };
};

const makeBatchimTips = (
  base: string,
  baseRom: string,
  batchim: string,
  batchimRom: string,
  syllable: string,
  syllableRom: string,
  pronNote?: string
): LangRecord => {
  const noteSuffix = pronNote ? ` ${pronNote}` : '';
  return {
    en: `Syllable [${base}]${baseRom} + Final Consonant [${batchim}]${batchimRom} combine into [${syllable}]${syllableRom}${noteSuffix}.`,
    vi: `Âm tiết [${base}]${baseRom} + Phụ âm cuối [${batchim}]${batchimRom} ghép thành [${syllable}]${syllableRom}${noteSuffix}.`,
    bn: `[${base}]${baseRom} + শেষ ব্যঞ্জনবর্ণ (বাচ্চিম) [${batchim}]${batchimRom} যুক্ত হয়ে [${syllable}]${syllableRom}${noteSuffix} তৈরি হয়।`,
    zh: `音节 [${base}]${baseRom} + 收音 [${batchim}]${batchimRom} 组合成 [${syllable}]${syllableRom}${noteSuffix}。`,
    ru: `Слог [${base}]${baseRom} + конечный согласный [${batchim}]${batchimRom} образуют [${syllable}]${syllableRom}${noteSuffix}.`,
    ja: `音節 [${base}]${baseRom} + パッチム [${batchim}]${batchimRom} が合わさって [${syllable}]${syllableRom}${noteSuffix} になります。`,
    mn: `[${base}]${baseRom} + дэвсгэр үсэг [${batchim}]${batchimRom} нийлж [${syllable}]${syllableRom}${noteSuffix} болно.`,
  };
};

const makeDoubleBatchimTips = (
  base: string,
  baseRom: string,
  b1: string,
  b2: string,
  pronounced: string,
  syllable: string,
  syllableRom: string,
  pronNote: string
): LangRecord => ({
  en: `[${base}]${baseRom} + Double Batchim [${b1}${b2}] makes [${syllable}]${syllableRom}. Pronounce [${pronounced}] ➔ ${pronNote}.`,
  vi: `[${base}]${baseRom} + Phụ âm cuối kép [${b1}${b2}] tạo thành [${syllable}]${syllableRom}. Phát âm [${pronounced}] ➔ ${pronNote}.`,
  bn: `[${base}]${baseRom} + যুক্ত বাচ্চিম [${b1}${b2}] মিলে [${syllable}]${syllableRom} হয়। [${pronounced}] উচ্চারণ করুন ➔ ${pronNote}।`,
  zh: `[${base}]${baseRom} + 双收音 [${b1}${b2}] 组成 [${syllable}]${syllableRom}。发 [${pronounced}] 音 ➔ ${pronNote}。`,
  ru: `[${base}]${baseRom} + двойной патчим [${b1}${b2}] образуют [${syllable}]${syllableRom}. Читается [${pronounced}] ➔ ${pronNote}.`,
  ja: `[${base}]${baseRom} + 二重パッチム [${b1}${b2}] で [${syllable}]${syllableRom}。発音は [${pronounced}] ➔ ${pronNote}。`,
  mn: `[${base}]${baseRom} + давхар дэвсгэр [${b1}${b2}] нийлж [${syllable}]${syllableRom} болно. [${pronounced}] гэж дуудна ➔ ${pronNote}.`,
});

